/* 학부모 리포트 자료 — 학생 화면과 **다른 말로** 쓴다.
 *
 * 학부모가 알고 싶은 것은 학생이 보는 것과 다르다.
 *   학생 : 오늘 뭘 하지 · 어디가 약하지 · 얼마나 남았지
 *   학부모: 꾸준히 하고 있나 · 늘고 있나 · 시험에서 몇 점 나올까 ·
 *           돈값을 하나 · 내가 뭘 해 주면 되나
 *
 * ■ 지켜야 할 것
 *   ① **숫자를 지어내지 않는다.** 모르면 "아직 모릅니다" 라고 쓴다.
 *      학부모에게 근거 없는 등급을 말하면 그 순간 신뢰가 끝난다.
 *   ② 훈계하지 않는다. "더 시켜야 합니다" 같은 말은 부모를 압박한다.
 *   ③ **부모가 할 수 있는 일**을 한 가지만 준다. 여러 개는 아무것도 안 하게 만든다.
 *   ④ 학생을 깎아내리지 않는다. 못한 주에도 사실만 적는다.
 */
window.PARENT = {

  /* ── 꾸준함을 어떻게 말할까 ────────────────────
     '며칠 했나' 는 부모가 바로 알아듣는 말이다. */
  /* ★ 2026-09-28 판정소 4차 — 학부모 화면은 **보고만** 한다. 수치·사실만, 부탁·조언·위로 없음. */
  streakSay: function (연속, 최근7) {
    if (연속 >= 2) return { t: 연속 + "일 연속", d: "최근 7일 중 " + 최근7 + "일" };
    if (최근7 >= 1) return { t: "최근 7일 중 " + 최근7 + "일", d: "" };
    return { t: "최근 7일 학습 0일", d: "" };
  },

  /* 「부모님이 해 주실 수 있는 한 가지」(advice)는 뺐다 — 부탁·조언이다(2026-09-28 대표님 「학부모한텐 걍 니트하게 보고만 해」) */

  /* ── 성적 이야기를 어떻게 할까 ────────────────
     ★ 근거 없는 등급을 말하지 않는다. 푼 문항이 적으면 그렇다고 쓴다. */
  scoreSay: function (푼문항, 정답률, 회차평균) {
    if (푼문항 < 30) {
      return { t: "데이터 부족",
               d: "푼 문항 " + 푼문항 + "개",
               tone: "wait" };
    }
    if (회차평균 != null) {
      return { t: "모의고사 평균 " + Math.round(회차평균) + "점",
               d: "25문항, 100점 만점",
               tone: "ok" };
    }
    return { t: "정답률 " + Math.round(정답률) + "%",
             d: "푼 문항 " + 푼문항 + "개 기준, 모의고사 기록 없음",
             tone: "ok" };
  }
};
