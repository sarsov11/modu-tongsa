/* 학부모 리포트 자료 — 학생 화면과 **다른 말로** 쓴다.
 *
 * 학부모가 알고 싶은 것은 학생이 보는 것과 다르다.
 *   학생 : 오늘 뭘 하지 · 어디가 약하지 · 얼마나 남았지
 *   학부모: 꾸준히 하고 있나 · 늘고 있나 · 시험에서 몇 점 나올까 ·
 *           돈값을 하나 · 내가 뭘 해 주면 되나
 *
 * ■ 지켜야 할 것
 *   ① **숫자를 지어내지 않는다.** 모르면 "아직 모릅니다" 라고 쓴다.
 *      학부모에게 근거 없는 등급을 말하면 그 순간 신뢰가 끝난다.
 *   ② 훈계하지 않는다. "더 시켜야 합니다" 같은 말은 부모를 압박한다.
 *   ③ **부모가 할 수 있는 일**을 한 가지만 준다. 여러 개는 아무것도 안 하게 만든다.
 *   ④ 학생을 깎아내리지 않는다. 못한 주에도 사실만 적는다.
 */
window.PARENT = {

  /* ── 꾸준함을 어떻게 말할까 ────────────────────
     '며칠 했나' 는 부모가 바로 알아듣는 말이다. */
  streakSay: function (연속, 최근7) {
    if (연속 >= 14) return { t: "습관이 잡혔습니다", d: "2주 넘게 이어 가고 있습니다." };
    if (연속 >= 7) return { t: "한 주를 채웠습니다", d: "이 흐름이 이어지면 습관이 됩니다." };
    if (연속 >= 3) return { t: "자리를 잡아 가는 중", d: "사흘째입니다. 일주일이 고비입니다." };
    if (최근7 >= 3) return { t: "띄엄띄엄 하고 있습니다", d: "최근 이레 중 " + 최근7 + "일 했습니다." };
    if (최근7 >= 1) return { t: "최근에 뜸합니다", d: "최근 이레 중 " + 최근7 + "일 했습니다." };
    return { t: "이번 주는 쉬었습니다", d: "다시 시작하기 좋은 때입니다." };
  },

  /* ── 부모가 할 수 있는 일 — **한 가지만** ──────
     상황에 따라 다른 한 마디. 여러 개를 주면 아무것도 안 한다. */
  advice: function (s) {
    if (s.연속 === 0 && s.최근7 === 0) {
      return { t: "오늘 저녁에 한 번만 같이 앉아 주세요",
               d: "하루 15분이면 끝납니다. 시작이 어려울 뿐입니다. " +
                  "'뭐 했어?' 보다 '같이 켜 볼까?' 가 낫습니다." };
    }
    if (s.dday != null && s.dday <= 10) {
      return { t: "매일 모의고사를 볼 시간을 확보해 주세요",
               d: "시험이 " + s.dday + "일 남아 하루 한 회씩 실전으로 풉니다. " +
                  "45분이 끊기지 않는 시간대를 정해 두면 좋습니다." };
    }
    if (s.정답률 != null && s.정답률 < 55) {
      return { t: "점수보다 '어제 뭐 틀렸는지' 를 물어봐 주세요",
               d: "지금은 틀리면서 배우는 구간입니다. 점수를 물으면 숨기게 되고, " +
                  "틀린 것을 물으면 설명하면서 한 번 더 봅니다." };
    }
    if (s.연속 >= 7) {
      return { t: "지금은 그냥 두시는 게 낫습니다",
               d: "스스로 이어 가고 있습니다. 이럴 때 참견하면 흐름이 끊깁니다. " +
                  "일주일에 한 번 이 리포트만 보셔도 됩니다." };
    }
    return { t: "하루 15분, 시간을 정해 주세요",
             d: "'언제 할지' 가 정해지면 '할지 말지' 를 고민하지 않습니다. " +
                "저녁 먹고 바로가 가장 잘 지켜집니다." };
  },

  /* ── 성적 이야기를 어떻게 할까 ────────────────
     ★ 근거 없는 등급을 말하지 않는다. 푼 문항이 적으면 그렇다고 쓴다. */
  scoreSay: function (푼문항, 정답률, 회차평균) {
    if (푼문항 < 30) {
      return { t: "아직 말씀드리기 이릅니다",
               d: "푼 문항이 " + 푼문항 + "개입니다. 50문항쯤 쌓이면 " +
                  "어디가 약한지 말씀드릴 수 있습니다.",
               tone: "wait" };
    }
    if (회차평균 != null) {
      return { t: "모의고사 평균 " + Math.round(회차평균) + "점",
               d: "학교 시험과 같은 25문항 100점으로 봅니다. " +
                  "회차가 쌓이면 오르내림보다 **흐름**을 보시면 됩니다.",
               tone: "ok" };
    }
    return { t: "정답률 " + Math.round(정답률) + "%",
             d: "지금까지 푼 " + 푼문항 + "문항 기준입니다. " +
                "아직 모의고사를 보지 않아 점수로는 말씀드리기 어렵습니다.",
             tone: "ok" };
  }
};
