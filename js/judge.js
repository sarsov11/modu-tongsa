  /* 앞말의 **받침**을 보고 조사를 고른다.
     한국어는 받침 유무로 은/는·이/가·을/를이 갈린다 —
     개념 이름을 끼우면서 조사를 안 맞추면 "비교우위이", "지위은" 이 된다. */
